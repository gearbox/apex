"""Explicit composition root for the process-local media ingest services."""

from __future__ import annotations

from typing import TYPE_CHECKING

from src.api.services.media_ingest.service import MediaIngestService

if TYPE_CHECKING:
    import asyncio

    from src.core.config import Settings


def _build(
    settings: Settings,
    *,
    max_input_bytes: int,
    video_slots: asyncio.Semaphore | None,
    image_slots: asyncio.Semaphore | None,
) -> MediaIngestService:
    """Single construction site so the user-upload and provider-output services cannot drift."""
    return MediaIngestService(
        max_image_megapixels=settings.image_max_input_megapixels,
        max_input_bytes=max_input_bytes,
        video_max_frames=settings.media_ingest_video_max_frames,
        video_max_edge=settings.media_ingest_video_max_edge,
        video_concurrency=settings.media_ingest_video_concurrency,
        image_concurrency=settings.media_ingest_image_concurrency,
        admission_wait_seconds=settings.media_ingest_admission_wait_seconds,
        video_deadline_seconds=settings.media_ingest_video_deadline_seconds,
        stage_timeout_seconds=settings.media_ingest_stage_timeout_seconds,
        max_animation_frames=settings.media_ingest_max_animation_frames,
        video_slots=video_slots,
        image_slots=image_slots,
    )


def build_media_ingest_service(
    settings: Settings,
    *,
    video_slots: asyncio.Semaphore | None = None,
    image_slots: asyncio.Semaphore | None = None,
) -> MediaIngestService:
    """Build the bounded service for user uploads (``MAX_UPLOAD_SIZE_MB`` byte budget).

    Args:
        settings: Validated application settings.
        video_slots: Optional shared video admission semaphore (default: own).
        image_slots: Optional shared image admission semaphore (default: own).
    """
    return _build(
        settings,
        max_input_bytes=settings.max_upload_size_bytes,
        video_slots=video_slots,
        image_slots=image_slots,
    )


def build_provider_video_ingest_service(
    settings: Settings,
    *,
    video_slots: asyncio.Semaphore | None = None,
    image_slots: asyncio.Semaphore | None = None,
) -> MediaIngestService:
    """Build the service that prepares videos generated by remote providers.

    Identical to :func:`build_media_ingest_service` except for the byte budget
    (``MEDIA_INGEST_PROVIDER_VIDEO_MAX_MB``). Pass the same semaphores to both
    so the process keeps a single ffmpeg concurrency budget.

    Args:
        settings: Validated application settings.
        video_slots: Optional shared video admission semaphore (default: own).
        image_slots: Optional shared image admission semaphore (default: own).
    """
    return _build(
        settings,
        max_input_bytes=settings.media_ingest_provider_video_max_bytes,
        video_slots=video_slots,
        image_slots=image_slots,
    )
